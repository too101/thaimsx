; lookup) ไม่เคยมีเส้นทางสำหรับแถวตัวเลขหรือสถานะกด Shift เลยตั้งแต่แรก (fallback เป็นปล่อยผ่านเสมอ)
;
; disassemble MSXTHA102_original_16k.rom ซ้ำ (จุดเข้า Thai lookup จริงที่ $4E53, ไม่ใช่ $4D4C/$4D71
; ที่เคยเข้าใจว่าเป็น "handler หลัก" -- สองจุดนั้นแท้จริงคือ handler ของ "ตาราง dispatch เริ่มต้น" ที่
; $4C7A ซึ่งใช้เฉพาะตอน THAI_MODE ปิดอยู่ หรือกด CTRL ค้าง เท่านั้น) พบว่าต้นฉบับมีตาราง scan-code
; ->font-code อยู่ "สองตาราง" ที่ยาว 48 ไบต์เท่ากันทั้งคู่ (ครอบคลุม scan $00-$2F: แถวตัวเลข+row1+แถว
