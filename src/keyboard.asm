; ที่ offset $16, ROW1_TABLE เดิมคือ slice ที่ offset $0A พอดี -- $4EAB+$16=$4EC1 และ $4EAB+$0A=$4EB5
; ตรงกับตำแหน่งที่เคยบันทึกไว้เป๊ะ) เพียงแต่ไม่เคยสังเกตมาก่อนว่าเป็นตารางเดียวกันที่ยาวกว่าที่ใช้จริง
; และไม่เคยรู้มาก่อนว่ามีตารางกด Shift คู่กันอยู่เลย (ดูโค้ดจริงที่ $4E53: อ่าน SHIFT_STATE bit0 เลือก
; ระหว่างสองตารางนี้ ก่อนจะ index ด้วย scan code ตรง ๆ -- ไม่ใช่ compact index แบบที่พอร์ตไว้เดิม)
;
; นอกจากนี้ยังพบว่าต้นฉบับเช็ค CTRL (bit1) และ GRAPH (bit2) ของ SHIFT_STATE ก่อนเข้า Thai lookup เสมอ
; (ที่ $4D17-$4D21): ถ้ากด CTRL หรือ GRAPH ค้างอยู่ -- ปล่อยผ่านเป็นอังกฤษ/กราฟิกปกติเสมอ ไม่ว่า
; THAI_MODE/INPUT_MODE จะเป็นอะไร (เวอร์ชันนี้ไม่ implement การประกอบอักษรกราฟิกพิเศษของ GRAPH ต้นฉบับ
; -- ปล่อยผ่านให้ BIOS จัดการปกติแทน ซึ่งเพียงพอและถูกต้องสำหรับขอบเขต Phase 3 ส่วนที่ 1)
;
; แก้โดยรวม MAIN_ROW_TABLE/ROW1_TABLE เดิมเป็นตารางเดียว (THAI_UNSHIFTED_TABLE, 48 ไบต์ scan $00-$2F)
; และเพิ่มตารางใหม่ (THAI_SHIFTED_TABLE, 48 ไบต์ scan $00-$2F เท่ากัน) ดึงค่าจริงจาก ROM ต้นฉบับตรง ๆ
; ทั้งคู่ (ตาราง data ล้วน ๆ เหมือนเดิม ไม่ใช่กลไก implementation ที่เปราะบาง) เปลี่ยนลอจิกให้เช็ค
; CTRL/GRAPH ก่อน (ปล่อยผ่านถ้ากดค้าง) แล้วเลือกตารางตาม SHIFT bit0 แทนการเช็ค "AND 3 = 3" แบบเดิม
; (บั๊กจริงข้อ 9 แก้ขั้วถูกแล้ว แต่ยังไม่ครอบคลุมกรณีกด Shift ให้ได้อักษรไทยชุดที่สอง เพิ่งพบตอนนี้)
;
; *** ยังไม่ได้ implement (บันทึกไว้ตรง ๆ ไม่ปิดบัง) ***: กรณีพิเศษ 2 จุดในต้นฉบับที่ $4E5F-$4E86 (คีย์
; ผสมเฉพาะบางตัวที่เช็คแถว matrix เพิ่มอีกแถวหนึ่ง $FBE7 bit5 ร่วมกับ scan code เจาะจง $20/$25 ให้ผล
; font code พิเศษ $E5/$80) และ flag "sticky shift" ที่ $FCAB (ใช้ที่ $4E70 ให้ผลเหมือนกด Shift ค้างแม้
; ไม่ได้กดจริง) -- ทั้งสองดูเหมือนเป็นกลไกเสริมสำหรับปุ่มพิเศษที่ยังไม่ระบุแน่ชัด (ไม่ใช่ปุ่มมาตรฐานที่
; ผู้ใช้ทดสอบเจอ) และค่า font code $85 ที่ตาราง Shift มีเป็นพิเศษ (push สองไบต์ $D1+$E9 ติดกัน ที่
; $4E8E-$4E99) เก็บไว้เป็นงานค้างสำหรับตอนพบปัญหาจริงจากผู้ใช้ค่อยไล่ต่อ
KEYC_THAI_TABLE_N equ $30  ; ตาราง Thai unshifted/shifted ครอบคลุม scan $00-$2F (แถวตัวเลข+row1+แถว
                           ; อักษรหลัก รวมกัน 48 ไบต์) ยืนยันจาก disassembly จริงที่ $4E53 ($4EAB/$4EDB)

; KEYC_HOOK_REAL -- เนื้อ logic จริง (เดิมชื่อ KEYC_HOOK ก่อนบั๊กข้อ 7) ยังอยู่ใน cartridge ROM
; (page 1) เหมือนเดิมทุกประการ -- *** อัปเดตหลังการออกแบบใหม่ (RST 30H/CALLF, ดู comment เต็มที่
; KEYC_INSTALL ด้านล่าง) *** ตอนนี้ H_KEYC ชี้มาที่นี่ตรง ๆ ผ่าน BIOS's official CALLF primitive
; (ไม่มี KEYC_TRAMPOLINE ใน RAM อีกต่อไป -- ดู DEAD CODE ด้านล่าง) CALLF เป็นผู้จัดการสลับ page 1
; ไป-กลับให้เองทั้งหมดก่อนเรียกเข้ามาถึงตรงนี้ (ยืนยันจาก disassembly จริงว่าใช้ shadow register set)
; จึงยังปลอดภัยที่จะอ่าน MAIN_ROW_TABLE/ROW1_TABLE ตรง ๆ (ROM เดียวกัน) เหมือนเดิมทุกประการ
;
; สัญญา (contract) ปัจจุบันกับ CALLF: เข้ามาด้วย A=C=scan code, HL=ค่าเดิมจากผู้เรียก (ต้องคืนค่า
; เป๊ะทุกสาขา ดูบั๊กจริงข้อ 1) -- ออกด้วย "ld a,SAFE_DISPATCH_A; scf; ret" ถ้าจัดการคีย์นี้เองสำเร็จ
; แล้ว (บั๊กจริงข้อ 10: ค่า A ต้องเป็น SAFE_DISPATCH_A เท่านั้น เพราะ CALLF กลับไปหา BIOS caller จริง
; เสมอไม่ว่า carry จะเป็นอะไร -- BIOS's post-hook dispatch table (0x1028) จึง "เดินต่อเสมอ" ไม่ถูกข้าม
; อีกต่อไปเหมือนสมัย trampoline เดิม, carry มีผลแค่เป็น "สัญญาณภายใน" ที่โค้ดของเราใช้เองด้านล่าง
; ไม่ได้ถูก CALLF หรือ BIOS อ่านโดยตรง) หรือ "ld a,c; or a; ret" (carry=0) ถ้าต้องการปล่อยผ่าน -- A=C
; เดิม (scan code) ทำให้ BIOS's เดินตาราง dispatch ของมันเองแบบ default (เหมือนไม่มี hook เลย) ซึ่ง
; ทำหน้าที่แทน "ปล่อยผ่าน" โดยธรรมชาติ (ไม่มี PREV_KEYC ให้ chain หาอีกต่อไปในเส้นทางนี้ -- PREV_KEYC
; ใช้แค่ตอน KEYC_UNINSTALL คืนค่า H_KEYC ตอน THAIOFF เท่านั้น)
KEYC_BODY:
	push hl
	ld a,c
	cp KEYC_TOGGLE_CODE
	jp z,.toggle
	; --- 9.20: BS/DEL ระหว่างรับบรรทัดขณะ PRINTON -> ดันโค้ดส่วนตัวแทน ให้ PRINTHOOK ลบพร้อมสระบน/ล่าง ---
	; (INLIN_ACTIVE ตั้งเฉพาะตอน PRINTON เปิดและ BIOS กำลังรับบรรทัด -- นอกนั้น BS/DEL ปกติทุกประการ)
	cp KEY_BS_SCAN
	jr z,.bsdel
	cp KEY_DEL_SCAN
	jr nz,.not_bsdel
.bsdel:
	ld a,(ix+INLIN_ACTIVE)
	or a
	jr z,.not_bsdel
	ld a,(SHIFT_STATE)
	bit 1,a
	jr z,.not_bsdel             ; CTRL กดอยู่ -- ปล่อยผ่าน
	ld a,c
	cp KEY_BS_SCAN
	ld a,THAI_BS_CODE
	jr z,.bsdel_push
	ld a,THAI_DEL_CODE
.bsdel_push:
	call QUEUE_PUSH_CHAR
	jp .push_after
.not_bsdel:

	; --- ส่วนที่ 2: พิมพ์อักษรไทยแบบเรียบ (ดูหัวข้อ 5) ---
	ld a,(ix+THAI_MODE)
	or a
	jp z,.passthrough          ; cartridge ยังไม่ได้ THAION -- ปล่อยผ่านตามปกติ
	; ---- 9.30 (A1): GRAPH+A..Z พิมพ์คำสั่ง BASIC ทั้งคำ (+SHIFT = ชุดที่สอง) -- ตามต้นฉบับ $4D17-$4D21 ->
	; $4F0B: ทำงานทุกครั้งที่ THAION อยู่ ไม่ว่าจะพิมพ์ไทยหรืออังกฤษ (CTRL+GRAPH ปล่อยผ่าน)
	ld a,(SHIFT_STATE)
	bit 2,a
	jr nz,.no_kw                ; GRAPH ไม่ได้กด
	bit 1,a
	jr z,.no_kw                 ; CTRL กดด้วย -- ปล่อยผ่าน
	ld a,c
	sub KEY_A_SCAN
	jr c,.no_kw
	cp 26
	jr nc,.no_kw
	ld b,a                      ; B = ลำดับตัวอักษร 0..25
	ld hl,KW_TABLE_N
	ld a,(SHIFT_STATE)
	bit 0,a
	jr nz,.kw_find              ; SHIFT ไม่ได้กด
	ld hl,KW_TABLE_S
.kw_find:
	inc b
	jr .kw_next
.kw_skip:
	bit 7,(hl)
	inc hl
	jr z,.kw_skip
.kw_next:
	djnz .kw_skip
.kw_push:
	ld a,(hl)
	push af
	and $7F
	push hl
	call QUEUE_PUSH_CHAR
	pop hl
	inc hl
	pop af
	rlca
	jr nc,.kw_push
	jp .push_after
.no_kw:
	ld a,(ix+INPUT_MODE)
	or a
	jr z,.passthrough          ; ผู้ใช้ปิดโหมดประกอบอักษร (INPUTOFF/ยังไม่ toggle) -- ปล่อยผ่าน
	; ---- 9.31 (A3): กด Enter ใน direct mode (CURLIN=$FFFF) ขณะพิมพ์ไทย -> กลับเป็นอังกฤษเอง แล้วปล่อยผ่าน
	; ให้ BIOS ดัน CR ตามปกติ (ต้นฉบับ $50F6-$510C: คำสั่ง BASIC พิมพ์เป็นอังกฤษ) -- ตอนโปรแกรมทำงาน (INPUT)
	; ไม่สลับ -- ผู้ใช้ขอให้ทำตามต้นฉบับ (เดิมบั๊กข้อ 12 รอบสองคืออาการเดียวกันแต่เกิดจาก RAM ชน ไม่ได้ตั้งใจ)
	ld a,c
	cp KEY_RET_SCAN
	jr nz,.not_ret
	ld hl,(CURLIN)
	inc hl
	ld a,h
	or l
	jr nz,.passthrough
	xor a
	call SET_INPUT_MODE
	jr .passthrough
.not_ret:
	; *** บั๊กจริงข้อ 9 (แก้แล้ว) + บั๊กจริงข้อ 11 (แก้แล้ว, แทนที่ตรรกะเช็ค SHIFT_STATE เดิมทั้งหมด) ***
	; ดู comment ใหญ่เหนือ KEYC_THAI_TABLE_N ด้านบนสำหรับรายละเอียดการวิเคราะห์จาก disassembly จริง
	; ($4D10-$4E53 ของต้นฉบับ) -- เช็คทีละบิตตรง ๆ (bit0=SHIFT, bit1=CTRL, bit2=GRAPH, active-low)
	; แทนการเช็ค "AND 3" แบบเดิม เพราะต้องแยกแยะ CTRL/GRAPH (ปล่อยผ่านเสมอ) ออกจาก SHIFT (ต้องเลือก
	; ตารางที่สองแทนที่จะปล่อยผ่าน) ให้ถูกต้อง ซึ่ง "AND 3" เดิมแยกไม่ได้ (รวม SHIFT+CTRL เป็นค่าเดียว)
	ld a,c
	cp KEYC_THAI_TABLE_N
	jr nc,.passthrough          ; scan >= $30 -- นอกช่วงตาราง Thai (บั๊กจริงข้อ 11) ปล่อยผ่านตามปกติ

	ld a,(SHIFT_STATE)
	bit 1,a
	jr z,.passthrough           ; CTRL กดอยู่ (bit1=0, active-low) -- ปล่อยผ่านเสมอ (ตรงกับต้นฉบับ $4D1C)
	bit 2,a
	jr z,.passthrough           ; GRAPH กดอยู่ (bit2=0) -- ปล่อยผ่านเสมอ (ตรงกับต้นฉบับ $4D1F -- ไม่
	                            ; implement การประกอบอักษรกราฟิกพิเศษของ GRAPH ในต้นฉบับ นอกขอบเขต
	                            ; Phase 3 ส่วนที่ 1)
	; ---- 9.32 (D): ตรงตามต้นฉบับ $4E53-$4EAA ----
	; D1: CAPS LOCK เปิดอยู่ (CAPST, BIOS สลับให้เองเมื่อกด CAPS) = ล็อก Shift ไทย -> ใช้ตารางกด Shift
	; D2: กดปุ่ม scan $15 (matrix แถว 2 bit 5 -- ปุ่มนี้ไม่มีอักษรไทยของตัวเอง) ค้างไว้แล้วกด
	;     J (scan $20) = ๅ ($E5) / กับ Shift หรือ CAPS: O (scan $25) = ฦๅ ($80)
	; D3 (9.34 ผู้ใช้ขอ): ไม่แยกเป็น 2 ไบต์แบบต้นฉบับ -- ำ เก็บเป็น $D3 ตัวเดียว, Shift+7 = ฿ ($DF)
	ld hl,THAI_UNSHIFTED_TABLE
	bit 0,a
	jr z,.shifted               ; SHIFT กดอยู่ (bit0=0)
	ld a,(CAPST)
	or a
	jr nz,.shifted              ; D1
	ld a,(NEWKEY_R2)
	bit 5,a
	jr nz,.lookup               ; ไม่ได้กดปุ่ม $15 ค้าง
	ld a,c
	cp $20
	jr nz,.lookup
	ld a,$E5                    ; D2: ๅ
	jr .push1
.shifted:
	ld hl,THAI_SHIFTED_TABLE    ; *** บั๊กจริงข้อ 11 *** ตารางกด Shift
	ld a,(NEWKEY_R2)
	bit 5,a
	jr nz,.lookup
	ld a,c
	cp $25
	jr nz,.lookup
	ld a,$80                    ; D2: ฦๅ
	jr .push1
.lookup:
	; HL = ตารางที่เลือก, index ด้วย scan code ตรง ๆ -- *** ต้องคง C (scan code เดิม) ไว้ (บั๊กจริงข้อ 3) ***
	push bc
	ld b,0
	add hl,bc
	ld a,(hl)
	pop bc
	cp $FF
	jr z,.push_after            ; ปุ่ม $15 -- ต้นฉบับไม่พิมพ์อะไร (ใช้เป็นปุ่มกดค้างของ D2)
.push1:
	call QUEUE_PUSH_CHAR        ; ดัน font code ของอักษรไทยเข้าคิวคีย์บอร์ด
.push_after:
	pop hl                      ; *** คืน HL ให้ตรงเดิมเสมอ (บั๊กจริงข้อ 1) ***
	ld a,SAFE_DISPATCH_A        ; *** บั๊กจริงข้อ 10 -- ต้องกำหนด A ให้ปลอดภัยก่อน SCF เสมอ ***
	scf                         ; carry=1 = "จัดการคีย์นี้แล้ว" (BIOS ยังเดินตาราง dispatch เองต่อ
	ret                         ; แต่ A=SAFE_DISPATCH_A ทำให้มันทิ้งคีย์แทนที่จะดันซ้ำ)

.passthrough:
	ld a,c                      ; *** คืน A = scan code เดิมเสมอ (บั๊กจริงข้อ 3 ดูหัวข้อ 4) ***
	pop hl
	or a                        ; carry=0 = "ปล่อยผ่าน" (trampoline จะคืน page 1 แล้ว JP PREV_KEYC ให้)
	ret

.toggle:
	pop hl                    ; *** ต้องคืน HL ให้ตรงเดิมเสมอ แม้แต่ในสาขานี้ -- ดูบั๊กจริงข้อ 1
	; ต่อจากนี้ห้ามใช้ HL อีกเด็ดขาด ใช้ absolute addressing ล้วน ๆ แทน (LD A,(nn)/LD (nn),A)
	ld a,(ix+INPUT_MODE)
	cpl
	call SET_INPUT_MODE        ; 9.30: ตั้ง flag + LED + cursor (ใช้ร่วมกับ Enter ใน direct mode)
	ld a,SAFE_DISPATCH_A      ; *** บั๊กจริงข้อ 10 -- เหมือนกับ .lookup ด้านบน (ค่า A จาก OUT ($A1)
	                          ; เป็นขยะสำหรับตาราง dispatch ของ BIOS ต้องเขียนทับก่อน SCF เสมอ) ***
	scf                       ; carry=1 = "จัดการคีย์นี้แล้ว"
	ret


; GET_MY_SLOT -- หา slot ID ของ cartridge นี้เอง (ใช้จาก KEYC_INSTALL เท่านั้น ตอนนั้น page 1
; คือ ROM ของเราแน่นอนอยู่แล้ว เพราะกำลังรันมาจาก CALL THAION -- logic เดียวกับที่ฝังซ้ำไว้ใน
; KEYC_TRAMPOLINE_SRC ด้านบน แยกเป็น routine ต่างหากที่นี่เพื่อไม่ต้องเขียนซ้ำสองที่ในเนื้อ ROM
; แต่ตัว trampoline เองห้ามเรียก routine นี้เด็ดขาด ดู comment ด้านบน)
; SET_INPUT_MODE: A = ค่าใหม่ของ INPUT_MODE (0/$FF) -- ตั้ง flag, ไฟ LED (PSG r15 bit7) และวาด cursor ใหม่
; ทำลาย AF เท่านั้น
SET_INPUT_MODE:
	push bc
	ld (ix+INPUT_MODE),a
	ld b,a
	ld a,15
	out ($A0),a
	in a,($A2)
	and $7F
	ld c,a
	ld a,b
	and $80
	or c
	out ($A1),a
	call CUR_REDRAW           ; 9.21: เปลี่ยนรูป cursor ทันที (คงทุก register)
	pop bc
	ret

GET_MY_SLOT:
	call RSLREG
	rrca
	rrca
	and 3
	ld c,a
	ld b,0
	ld hl,EXPTBL
	add hl,bc
	ld a,(hl)
	and $80
	or c
	ret p
	ld c,a
	inc hl
	inc hl
	inc hl
	inc hl
	ld a,(hl)
	and $0C
	or c
	ret

; ---- ติดตั้ง/ถอด hook (เรียกจาก CMD_THAION / CMD_THAIOFF ใน thaicmd.asm) ----
; DI/EI ครอบการเขียนทั้งหมด + เรียงลำดับให้ "ทุกจังหวะระหว่างเขียนยังเป็นโค้ดที่ปลอดภัยเสมอ"
;
; *** การออกแบบใหม่ (RST 30H / CALLF) -- แทนที่ trampoline มือเขียนเองของบั๊กข้อ 7/8 ทั้งหมด ***
; หลังบั๊กข้อ 8 (ENASLT เองทับ C ตอน slot expand) แก้แล้ว ผู้ใช้ยืนยันว่ายังพิมพ์ไม่ได้บนเครื่องจริง
; อยู่ดี (ไม่ทราบสาเหตุใหม่ที่แน่ชัด) -- ผู้ใช้ให้ MSXTHA102_MSX2_porting_notes.md มา ซึ่งเป็นบันทึก
; ของการ patch ROM ต้นฉบับ (MSXTHA102) ให้ใช้ได้จริงบน MSX2 (v50-v62, ยืนยันว่าใช้งานได้จริง) --
; เทคนิคของเขาไม่ได้เขียน trampoline เอง แต่ patch hook slot โดยตรงด้วย **RST 30H** (= CALLF, BIOS
; primitive อย่างเป็นทางการสำหรับเรียกข้าม slot, เอกสาร: "ตัว installer เขียน F7 <slot> <lo> <hi>
; C9 ลงแต่ละ hook") -- ตรวจสอบ disassembly จริงของ CALLF ใน MSX1_bios.rom (0x0030 -> JP 0x0205)
; แล้วพบเหตุผลชัดเจนว่าทำไมวิธีนี้ปลอดภัยกว่า trampoline มือเขียนของเราเอง: CALLF สลับไปใช้
; **shadow register set** (EXX / EX AF,AF') รอบ ๆ ช่วงที่มันเรียก ENASLT ภายในตัวมันเอง (ที่
; 0x027e/0x02a3 ซึ่งเป็น routine เดียวกับที่ ENASLT ใช้ ยืนยันจากบั๊กข้อ 7/8 เดิม) -- แปลว่า primary
; BC/DE/HL ของผู้เรียก (รวมถึง C=scan code ที่เป็นต้นเหตุบั๊กข้อ 8) ไม่มีทางถูกทับเลย เพราะ ENASLT
; ภายในไปทับ BC'/DE' (shadow) แทน ไม่ต้อง push/pop มือเองแบบที่เราพลาดในบั๊กข้อ 8 -- นี่คือกลไก
; "ทางการ" ที่ SPEC เดิม (บั๊กข้อ 7) เคยพิจารณาแล้วไม่ใช้เพราะกลัว dependency ของ RAM ที่ 0xF38C ที่
; verify ไม่ได้ใน flat-memory test harness -- ตอนนี้มีหลักฐานจริงจาก ROM ที่ใช้งานได้จริงบนเครื่อง
; จริงแล้วว่าใช้ได้ จึงเปลี่ยนมาใช้ -- KEYC_HOOK_REAL ไม่ต้องแก้อะไรเลย (ยังคง contract เดิมทุก
; ประการ: carry=1 -> จัดการแล้ว, carry=0+A=scan code เดิม -> ปล่อยผ่าน) เพราะตอนนี้ถูกเรียกตรง ๆ
; ผ่าน CALLF ซึ่งรับประกันว่า page 1 = slot ของเราแล้วตอนเข้าโค้ด (เหมือนที่ trampoline เดิมทำ แต่
; ทำโดย BIOS เอง ไม่ใช่โค้ดของเรา) -- KEYC_TRAMPOLINE_SRC/KEYC_TRAMPOLINE เดิมด้านล่างไม่ได้ลบทิ้ง
; (dead code เก็บไว้เผื่อย้อนกลับ) แต่ไม่ถูกเรียกใช้อีกต่อไป
;
; รูปแบบการ patch (5 ไบต์ต่อ hook slot, มาตรฐาน MSX hook table -- ตรวจสอบแล้วว่า H_KEYC ที่ยังไม่ได้
; ติดตั้งมีค่าเป็น C9 ทั้ง 5 ไบต์ [RET ซ้ำ] สอดคล้องกับทฤษฎีนี้): [$F7=RST 30H][slot][addr_lo]
; [addr_hi][$C9=RET] -- ลำดับการเขียนยังคงหลักการเดิม (ตอนติดตั้ง เขียนไบต์ที่ไม่ใช่ opcode แรกก่อน,
; เขียน $F7 ทีหลังสุด / ตอนถอด คืน opcode แรกเดิมก่อน) เพื่อความปลอดภัยถ้ามี interrupt แทรกกลางคัน

KEYC_INSTALL:                  ; 9.40: ติดตั้ง hook ทุกตัวจากตาราง HOOK_TABLE (เดิมเขียนแยกทีละตัว)
	di
	call GET_MY_SLOT
	ld (ix+MY_SLOT_ID),a
	ld hl,HOOK_TABLE
.hi_loop:
	ld e,(hl)
	inc hl
	ld d,(hl)                     ; DE = hook
	inc hl
	ld a,d
	or e
	jr z,.hi_done
	push de
	ld e,(hl)                     ; offset ที่สำรอง hook เดิมในบล็อก
	inc hl
	ld d,0
	call IX_DE                    ; DE = address สำรอง
	ld c,(hl)
	inc hl
	ld b,(hl)                     ; BC = จุดเข้าของเรา
	inc hl
	ex (sp),hl                    ; HL = hook, (sp) = ตาราง
	call HOOK_INSTALL
	pop hl
	jr .hi_loop
.hi_done:
	ei
	ret

KEYC_UNINSTALL:                ; 9.40: คืน hook เดิมทุกตัว
	di
	ld hl,HOOK_TABLE
.hu_loop:
	ld e,(hl)
	inc hl
	ld d,(hl)                     ; DE = hook
	inc hl
	ld a,d
	or e
	jr z,.hi_done
	ld a,(hl)
	inc hl
	inc hl
	inc hl
	push hl
	ld l,a
	ld h,0
	call IX_HL                    ; HL = ที่สำรอง
	ld bc,5
	ldir
	pop hl
	jr .hu_loop

; HOOK_TABLE: (hook, offset ที่สำรอง hook เดิมในบล็อก, จุดเข้าของเรา) -- จบด้วย 0
HOOK_TABLE:
	dw H_KEYC
	db PREV_KEYC
	dw KEYC_HOOK_REAL
	dw H_CHPUT
	db PREV_CHPUT
	dw PRINTHOOK
	dw H_CHGE
	db PREV_CHGE
	dw CHGE_HOOK
	dw H_PINL
	db PREV_PINL
	dw INLIN_HOOK
	dw H_INLI
	db PREV_INLI
	dw INLIN_HOOK
	dw H_DSPC
	db PREV_DSPC
	dw DSPC_HOOK
	dw H_ERAC
	db PREV_ERAC
	dw ERAC_HOOK
	dw H_TIMI
	db PREV_TIMI
	dw TIMI_HOOK
	dw H_GRPO
	db PREV_GRPO
	dw GRPO_HOOK
	dw H_LPTO
	db PREV_LPTO
	dw LPTO_HOOK
	dw 0

QUEUE_PUSH_CHAR:
	ld hl,(KEYQ_TAIL)
	ld (hl),a
	call KEYQ_ADVANCE          ; เลื่อน HL แบบ circular ภายในคิว (portable, ดู equates.asm)
	ld a,(KEYQ_END)
	cp l
	ret z                      ; คิวเต็ม -- เขียนช่องสุดท้ายไปแล้วแต่ไม่เลื่อน tail ต่อ (ตามต้นฉบับ)
	ld (KEYQ_TAIL),hl
	ret

; ---- ตาราง scan-code -> font code ของอักษรไทย (ดูหัวข้อ 5.1 และบั๊กจริงข้อ 11 สำหรับที่มา/การยืนยัน) --
; ดึงค่าจริงจาก MSXTHA102_original_16k.rom (ตาราง data ล้วน ๆ ไม่ใช่โค้ด/กลไก implementation) -- ตั้งแต่
; บั๊กจริงข้อ 11 รวม MAIN_ROW_TABLE/ROW1_TABLE เดิมเป็นตารางเดียวยาว 48 ไบต์ (index ด้วย scan code $00-
; $2F ตรง ๆ ครอบคลุมแถวตัวเลข+row1+แถวอักษรหลักพร้อมกัน ตามโครงสร้างจริงของต้นฉบับที่ $4EAB) พร้อมเพิ่ม
; ตารางคู่กันสำหรับตอนกด Shift ค้าง (จาก $4EDB, บั๊กจริงข้อ 11 เช่นกัน) -- $FF = ไม่มี mapping ไทยในคีย์
; นั้น (ปล่อยผ่านเป็นค่าเดิมของคีย์นั้น)
;
; THAI_UNSHIFTED_TABLE: 48 ไบต์ ตรงกับ scan code $00-$2F (ไม่กด Shift) -- จาก ROM offset 0x4EAB
THAI_UNSHIFTED_TABLE:
	db $A8,$A3,$2F,$5F,$C0,$B6,$D8,$D6   ; scan $00-$07 -- แถวตัวเลข (ยังไม่ได้ไล่ความหมายทีละตัว)
	db $A4,$B5,$A2,$AA,$82,$BA,$C5,$C7   ; scan $08-$0F -- แถวตัวเลข($08-$09)+row1 เริ่มต้น($0A-$0F)
	db $A7,$3B,$C1,$E3,$BD,$FF,$BF,$D4   ; scan $10-$17 -- row1 ต่อ($10-$15,DEAD=$FF)+main row เริ่มต้น
	db $E1,$A1,$D3,$B4,$E0,$E9,$C3,$E8   ; scan $18-$1F -- main row (B..I)
	db $D2,$CA,$B7,$D7,$B9,$C2,$E6,$BE   ; scan $20-$27 -- main row (J..Q)
	db $CB,$D0,$D5,$CD,$E4,$BB,$D1,$BC   ; scan $28-$2F -- main row (R..Z)
; main row (scan $16-$2F, A-Z ตามลำดับตัวอักษร) ยืนยันความหมายครบแล้ว (ดูหัวข้อ 5.1):
; A=ฟ(191) B=ิ(212) C=แ(225) D=ก(161) E=ำ(211) F=ด(180) G=เ(224) H=้(233) I=ร(195) J=่(232)
; K=า(210) L=ส(202) M=ท(183) N=ื(215) O=น(185) P=ย(194) Q=ๆ(230) R=พ(190) S=ห(203) T=ะ(208)
; U=ี(213) V=อ(205) W=ไ(228) X=ป(187) Y=ั(209) Z=ผ(188)
; row1 (scan $0A-$15): -=ข(162) ==ช(170) \=(graphic 130, ไม่ใช่ไทย) [=บ(186) ]=ล(197) ;=ว(199)
; '=ง(167) `=';'(ASCII,ไม่ใช่ไทย) ,=ม(193) .=ใ(227) /=ฝ(189) DEAD=ไม่มี mapping
; แถวตัวเลข (scan $00-$09): ยืนยันแค่ระดับไบต์จาก ROM ตรง ๆ (บั๊กจริงข้อ 11) ยังไม่ได้ไล่ความหมาย
; ทีละตัวอักษรเทียบกับ Kedmanee สาธารณะ (ไม่กระทบความถูกต้องของการพิมพ์ เพราะดึงมาจาก ROM ตรง ๆ)

; THAI_SHIFTED_TABLE: 48 ไบต์ ตรงกับ scan code $00-$2F เท่ากัน แต่ใช้ตอนกด Shift ค้าง (บั๊กจริงข้อ 11)
; -- จาก ROM offset 0x4EDB -- ยังไม่ได้ไล่ความหมายทีละตัวอักษร (เหตุผลเดียวกับแถวตัวเลขด้านบน)
THAI_SHIFTED_TABLE:
	db $F7,$A5,$F1,$F2,$F3,$F4,$D9,$DF   ; scan $00-$07 -- 9.34: Shift+7 = ฿ ($DF) ตามที่ผู้ใช้ขอ (ต้นฉบับ $85 = ั้)
	db $F5,$F6,$F8,$F9,$2D,$B0,$2C,$AB   ; scan $08-$0F
	db $2E,$2B,$B2,$CC,$C6,$FF,$C4,$FD   ; scan $10-$17 -- 9.24: Shift+' (ปุ่มเดียวกับ ง) = "." จริงตามแป้นเกษมณี (เดิม $DA)
	db $A9,$AF,$AE,$E2,$AC,$E7,$B3,$EB   ; scan $18-$1F
	db $C9,$C8,$3F,$EC,$CF,$AD,$F0,$B1   ; scan $20-$27
	db $A6,$B8,$EA,$CE,$22,$29,$ED,$28   ; scan $28-$2F
; หมายเหตุ: ต้นฉบับมีค่าพิเศษ $85 ที่ scan $07 ของตารางนี้ (push สองไบต์ $D1+$E9 ติดกันแทนไบต์เดียว --
