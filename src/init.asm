; ==========================================================================
; init.asm -- INIT vector: เรียกตอน cold boot โดย BIOS (ก่อน BASIC พร้อมใช้งาน)
;
; *** อัปเดต (คำขอผู้ใช้: banner ตอน boot + THAION เป็น default) ***
;
; สืบสวนจริงบน openMSX (จำลอง cold boot เต็มรูปแบบ ไม่ใช่แค่เรียก INIT ตรง ๆ แบบ harness เดิม)
; พบข้อเท็จจริงสำคัญ 3 ข้อที่ทำให้วิธี "ง่ายที่สุด" (พิมพ์ผ่าน CHPUT ตรง ๆ ใน INIT, หรือตั้ง flag/โหลด
; ฟอนต์/ติดตั้ง hook ตรง ๆ ใน INIT) ใช้ไม่ได้จริง:
;
; 1) INIT ของเราถูกเรียกจริง (ยืนยันด้วยการเปลี่ยนสี border ผ่าน VDP port ตรง ๆ ใน INIT แล้วเห็นสี
;    เปลี่ยนจริงบน screenshot) แต่ถูกเรียก "หลัง" BIOS แสดง splash แรกของมันเอง ("MSX system / version
;    1.0 / Copyright...") ไปแล้ว -- ไม่ใช่ก่อนอย่างที่เข้าใจไว้แต่แรก
; 2) ไม่ว่าจะพิมพ์ข้อความผ่าน CHPUT ตรง ๆ ใน INIT (จะมี call INITXT ก่อนหรือไม่ก็ตาม) ข้อความนั้นก็ถูก
;    บัง/ลบไปเสมอ ไม่รอดถึงจอสุดท้าย -- ยืนยันด้วย screenshot ที่ t=4s เห็นแต่ "MSX BASIC/Copyright/
;    Bytes free/Ok" ปกติ ไม่มีข้อความของเราเลย -- สาเหตุคือ BIOS's เอง "ยังมีขั้นตอนพิมพ์ banner จริง
;    ของระบบต่ออีกหลังจาก INIT ของเรา return กลับไป" (เรียก INITXT ซ้ำ + พิมพ์ "MSX BASIC/Copyright/
;    Bytes free" ของมันเอง) ซึ่งเคลียร์จอทับข้อความของเราไปหมด เหมือนกับเหตุผลเดียวกับบั๊กจริงข้อ 12
;    (การเขียนอะไรก็ตามที่ต้องพึ่งจังหวะ/ลำดับภายในของ boot sequence ของ BIOS เอง ไม่น่าเชื่อถือ)
; 3) รอมต้นฉบับ (MSXTHA102) แก้ปัญหานี้ด้วยการ hijack stack return address ให้กระโดดข้ามขั้นตอน
;    banner ของ BIOS เองไปเลย (ยืนยันจากผู้ใช้ว่า ROM เดิมค้างอยู่ที่จอ splash ของตัวเองตลอด ไม่เคยโชว์
;    banner ปกติของระบบเลย) -- นี่คือเทคนิค "internal address / stack hijack" แบบเดียวกับที่หลักการ
;    ออกแบบของโปรเจกต์นี้ (section 0) ห้ามใช้ตั้งแต่ต้น และเป็นสาเหตุของบั๊กข้อ 7/8 ที่เพิ่งแก้ไปเอง
;    ในเซสชันนี้ -- จึงตัดสินใจไม่เลียนแบบเทคนิคนี้
;
; วิธีแก้ที่เลือก (safe, portable, ไม่พึ่ง internal BIOS address ใด ๆ เลย): "stuff" ตัวอักษรเข้าคิว
; คีย์บอร์ด (keyboard queue ที่ $FBF0, official/documented system variable, ใช้ QUEUE_PUSH_CHAR ตัว
; เดียวกับที่ผ่านการทดสอบมาเต็มที่ตลอดทั้งโปรเจกต์สำหรับพิมพ์อักษรไทยจริง) ให้เป็นเหมือนผู้ใช้พิมพ์คำสั่ง
; "CALL THAION:?"Thai BASIC version 1.0"" เองทันทีที่ Ok prompt พร้อมรับ input -- วิธีนี้ปล่อยให้ BIOS
; boot ปกติสมบูรณ์ทุกขั้นตอนโดยไม่ถูกรบกวนเลย (ไม่เสี่ยง hang/ผิดเพี้ยนข้าม BIOS version เหมือนข้อ 3)
; แล้วอาศัยกลไกมาตรฐานของ BASIC เอง (อ่านคิวคีย์บอร์ดที่ Ok prompt) รันคำสั่งของเราหลังบูตเสร็จสมบูรณ์
; แล้วเท่านั้น -- ข้อความ/การเปิดใช้ Thai mode จึง "รอด" อยู่บนจอจริง เพราะไม่มีขั้นตอนใดของ BIOS ที่
; เคลียร์จอ/คิวหลังจุดนี้อีกแล้ว (Ok prompt คือจุดสุดท้ายของ cold boot)
;
; CALL THAION (ไม่ใช่การตั้ง flag/โหลดฟอนต์/ติดตั้ง hook ตรง ๆ ใน INIT) ถูกเลือกเพราะเหตุผลเดียวกับ
; ข้อ 2 ด้านบน: การโหลดฟอนต์เข้า VRAM หรือติดตั้ง H.KEYC hook ตอน INIT (ก่อน BIOS's เองเรียก INITXT
; รอบสุดท้าย) มีความเสี่ยงเดียวกันที่จะถูกขั้นตอน boot ที่เหลือของ BIOS เขียนทับ/รีเซ็ตอีก -- การให้
; BASIC "พิมพ์" CALL THAION เองหลังบูตเสร็จ รับประกันว่า CMD_THAION (โค้ดเดิมที่ทดสอบมาเต็มที่แล้ว)
; ทำงานในบริบทเดียวกับตอนผู้ใช้พิมพ์เองทุกประการ ไม่มีความเสี่ยงเรื่องจังหวะ boot เลย
;
; ยืนยันแล้วว่าต้องมี "CALL " นำหน้าเสมอ (ทดสอบพิมพ์ "thaion" เปล่า ๆ ไม่มี CALL แล้วได้ "Syntax
; error" จริงบน openMSX -- STATEMENT vector ของเราไม่ถูกเรียกถ้าไม่มี CALL นำหน้า)
;
; ขนาดคิวคีย์บอร์ดจริง = 40 ไบต์ (ยืนยันจาก disassembly ของ KEYQ_ADVANCE ที่ 0x10C2 ใน SPEC_TH.md
; หัวข้อ 9.9: wrap เมื่อ L ถึง 0x18 นับจาก $FBF0 = (0x100-0xF0)+0x18 = 40 ไบต์) -- ข้อความรวม "CALL
; THAION:?"Thai BASIC version 1.0"\r" ยาว 38 ไบต์ อยู่ในขอบเขตปลอดภัย (ไม่ auto-enable INPUTON ด้วย
; เพราะคำขอผู้ใช้ระบุแค่ "thaion เป็น default" -- โหมดพิมพ์ไทยจริง (INPUTON) ยังคงต้องกดปุ่มสลับโหมด
; เองตามปกติ เหมือนการใช้งานทั่วไป ไม่ใช่ auto-on ทั้งคู่)
;
; *** บั๊กจริงข้อ 13 (แก้แล้ว) -- "มีตัว C เกินมาทั้งที่ยังไม่ได้กดอะไร" (รายงานจากผู้ใช้หลังทดสอบจริง) ***
; สืบสวนด้วย debugger จริงบน openMSX (ตั้ง breakpoint ที่ INIT entry และที่ ret ท้าย stuffloop แล้ว dump
; KEYQ_TAIL/GETPNT/เนื้อคิวดิบทุกครั้งที่ hit) พบว่า **BIOS เรียก cartridge INIT ของเราถึง 2 ครั้ง**
; ระหว่าง cold boot จริง (ไม่ใช่ครั้งเดียวอย่างที่สมมติไว้แต่แรก -- นี่คือพฤติกรรมมาตรฐานที่รู้จักกันดีของ
; MSX BIOS: มีรอบสแกนสล็อตเบื้องต้นก่อนกำหนด RAM/ระบบเต็มรูปแบบ แล้วมีรอบ INIT จริงอีกที คาร์ทริดจ์ที่ดี
; ต้องทนต่อการถูกเรียก INIT ซ้ำได้เสมอ) -- รอบแรก stuff ครบ 38 ไบต์ปกติ (tail จบที่ $FC16) แต่รอบที่ 2
; เริ่ม stuff ซ้ำจาก BOOT_AUTOEXEC ใหม่ทั้งหมดโดยไม่เช็คอะไรก่อนเลย: ไบต์แรก 'C' เขียนลงช่องว่างที่เหลือ
; (index 38) สำเร็จ, ไบต์ที่ 2 'A' ทำให้คิว "เต็ม" (wrap กลับมาชนตำแหน่ง GETPNT เดิมที่ $FBF0) ทำให้
; QUEUE_PUSH_CHAR หยุดเลื่อน tail แต่ loop **ไม่เช็คค่าที่ QUEUE_PUSH_CHAR คืนมาเลย** จึงเดินลูปต่อจนครบ
; ทุกตัวอักษรที่เหลือ เขียนทับช่องเดิม (index 39) ซ้ำไปเรื่อย ๆ จนตัวสุดท้ายที่เขียนทับค้างไว้คือ CR --
; ผลคือคิวจริงกลายเป็น [...บรรทัดคำสั่งที่ถูกต้อง 38 ไบต์...] + "C" + CR ซึ่ง BASIC อ่านเป็น "บรรทัดถัดไป"
; หลัง Ok แรกพอดี = พิมพ์ "C" แล้ว Enter เอง โดยผู้ใช้ไม่ได้กดอะไรเลย (แล้วน่าจะตามด้วย Syntax error +
; Ok อีกรอบ ซึ่งตรงกับ "double Ok" ที่เคยสังเกตแต่ยังไม่ได้สืบสวนตอน verify ครั้งก่อน)
;
; วิธีแก้ (portable, ไม่เพิ่มตัวแปร RAM ใหม่ ไม่พึ่ง internal address ใด ๆ เพิ่มเติม): เช็ค idempotency
; ด้วยตัวคิวคีย์บอร์ดเองตรง ๆ ก่อน stuff ทุกครั้ง -- ถ้า KEYQ_TAIL (ตำแหน่งเขียน) ไม่เท่ากับ GETPNT/
; KEYQ_END (ตำแหน่งอ่าน) แปลว่าคิว "ไม่ว่าง" อยู่แล้ว (มีของค้างจากการ stuff รอบก่อนหน้า ที่ยังไม่ถูก
; BASIC อ่านไปหมด) จึงข้าม stuff รอบนี้ไปเลย -- ทนต่อ INIT ถูกเรียกกี่ครั้งก็ได้ (1, 2, หรือมากกว่า)
; เทียบแค่ byte ต่ำ (L) ของทั้งสอง pointer ตาม pattern เดียวกับที่ QUEUE_PUSH_CHAR ใช้เช็ค "คิวเต็ม" อยู่
; แล้ว (ดู src/keyboard.asm) -- edge case เดียวที่ไม่ครอบคลุม: ผู้ใช้กดคีย์ค้างตั้งแต่ก่อน INIT รอบแรก
; เป๊ะ ๆ (คิวไม่ว่างตั้งแต่ต้นจริง ๆ) ซึ่งพบยากมาก และถ้าเกิดขึ้นผลคือแค่ auto-exec ไม่ทำงาน (เงียบ ๆ
; ไม่มีอะไรพัง) ปลอดภัยกว่าการปล่อยให้คิวเพี้ยนแบบเดิมมาก
; ==========================================================================

INIT:
	; *** 9.22: เลิกดันคำสั่ง "CALL THAION:?..." เข้าคิวคีย์บอร์ด (ผู้ใช้ขอไม่ให้มีบรรทัดนั้นบนจอ) --
	; ติดตั้ง hook H.READ แทน: BASIC เรียก H.READ ก่อนพิมพ์ "Ok" ($4128 เหมือนกันทั้ง MSX1/2/2+) ซึ่ง
	; ครั้งแรกคือหลังพิมพ์ banner ของ MSX BASIC และหลัง INITXT เสร็จแล้ว (ฟอนต์ไม่โดนโหลดทับอีก) --
	; BOOT_HOOK ทำงานครั้งเดียว: คืน hook เดิม, THAION, พิมพ์ "Thai BASIC version 1.0"
	; INIT ถูกเรียกซ้ำได้ระหว่างบูต (บั๊กข้อ 13) -- ถ้า H.READ ชี้มาที่เราแล้วไม่ติดตั้งซ้ำ (ไม่งั้นจะ
	; สำรอง hook ของตัวเองเป็นค่าเดิม)
	xor a
	ld (THAI_MODE),a
	ld (INPUT_MODE),a
	ld (PRINT_MODE),a
	ld (PLOCK_MODE),a
	ld a,(H_READ)
	cp RST30_OPCODE
	jr nz,.init_hook
	ld hl,(H_READ+2)
	ld de,BOOT_HOOK
	or a
	sbc hl,de
	ret z
.init_hook:
	call GET_MY_SLOT              ; ตอน INIT page 1 คือ slot ของเราแน่นอน
	ld (MY_SLOT_ID),a
	di
	ld hl,H_READ
	ld de,PREV_READ
	ld bc,BOOT_HOOK
	call HOOK_INSTALL
	ei
	ret

; ---- BOOT_HOOK (9.22) -- H.READ ครั้งแรกหลังบูต ----
BOOT_HOOK:
	push hl
	push de
	push bc
	push af
	di
	ld hl,PREV_READ               ; one-shot: คืน hook เดิมก่อน
	ld de,H_READ
	ld bc,5
	ldir
	ei
	call THAION_CORE
	ld a,(CSRX)                   ; ข้อความ "Bytes free" ของ MSX1 ไม่ขึ้นบรรทัดใหม่ให้ (BASIC ขึ้นให้เอง
	dec a                         ; หลัง H.READ) -- ขึ้นบรรทัดก่อนพิมพ์ banner ถ้า cursor ไม่อยู่ต้นบรรทัด
	jr z,.bh_col1
	ld a,13
	call CHPUT
	ld a,10
	call CHPUT
.bh_col1:
	ld hl,BOOT_BANNER
.bh_loop:
	ld a,(hl)
	or a
	jr z,.bh_done
	call CHPUT
	inc hl
	jr .bh_loop
.bh_done:
	pop af
	pop bc
	pop de
	pop hl
	jp H_READ                     ; ต่อไปยัง hook เดิม (ปกติคือ RET)

BOOT_BANNER:
	db "Thai BASIC version 1.0",13,10,0
